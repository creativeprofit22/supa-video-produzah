// Regenerates packages/video-project/src/motion-presets.data.ts from diffusion-studio-2.
//
// Usage: node --experimental-strip-types scripts/generate-motion-presets.mjs <diffusion-studio-2/lib/motion-presets.data.ts>
//
// Easing descriptor strings ("cubicBezier(a,b,c,d)", preset names) become structured `Easing`
// objects; times become integer microseconds. Units are unchanged: x/y offsets in layer
// widths/heights from rest, scale and opacity multipliers of rest, rotation degrees added to rest.
import { writeFileSync } from "node:fs";
import console from "node:console";
import process from "node:process";
import { fileURLToPath, pathToFileURL, URL } from "node:url";

const source = process.argv[2];
if (source === undefined) {
  console.error(
    "usage: node --experimental-strip-types scripts/generate-motion-presets.mjs <motion-presets.data.ts>",
  );
  process.exit(2);
}
const { PRESETS } = await import(pathToFileURL(source).href);
const PRESET_NAMES = new Set([
  "easeIn",
  "easeOut",
  "easeInOut",
  "gentle",
  "snappy",
  "bouncy",
  "strong",
]);

function easing(descriptor) {
  if (PRESET_NAMES.has(descriptor)) return { kind: "preset", name: descriptor };
  const bezier = /^cubicBezier\(([-\d.]+),([-\d.]+),([-\d.]+),([-\d.]+)\)$/.exec(descriptor);
  if (bezier !== null) {
    const [x1, y1, x2, y2] = bezier.slice(1, 5).map(Number);
    return { kind: "cubicBezier", x1, y1, x2, y2 };
  }
  throw new Error(`unsupported easing descriptor ${descriptor}`);
}

const out = {};
for (const [name, preset] of Object.entries(PRESETS).sort(([a], [b]) => a.localeCompare(b))) {
  const tracks = {};
  for (const property of ["x", "y", "scale", "rotation", "opacity"]) {
    const keys = preset.tracks[property];
    if (keys === undefined) continue;
    tracks[property] = keys.map((key) => ({
      timeMicroseconds: Math.round(key.time * 1_000_000),
      value: key.value,
      ...(key.easing === undefined ? {} : { easing: easing(key.easing) }),
    }));
  }
  out[name] = {
    source: `diffusion-studio-2 ${preset.source.file} (${preset.source.element})`,
    durationMicroseconds: Math.round(preset.duration * 1_000_000),
    tracks,
  };
}

const target = fileURLToPath(
  new URL("../packages/video-project/src/motion-presets.data.ts", import.meta.url),
);
writeFileSync(
  target,
  `// GENERATED by scripts/generate-motion-presets.mjs from diffusion-studio-2 lib/motion-presets.data.ts: do not edit.
// Units: x/y offsets in layer widths/heights from rest, scale and opacity multipliers of rest,
// rotation degrees added to rest; times in microseconds from the preset start.
import type { MotionPresetData } from "./motion-presets.js";

export const MOTION_PRESET_DATA = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, MotionPresetData>;
`,
);
console.log(`wrote ${Object.keys(out).length} presets to ${target}`);

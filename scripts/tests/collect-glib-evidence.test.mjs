test("actual workflow pipeline preserves Cargo failure before tee failure", (t) => {
  const { root } = fixture(t);
  const workflow = readFileSync(new URL("../../.github/workflows/ci.yml", import.meta.url), "utf8");
  const block = workflow
    .split("        id: all_feature_tests\n")[1]
    .split("        run: |\n")[1]
    .split("\n\n")[0]
    .replace(/^          /gm, "");
  mkdirSync(join(root, ".cache/p1-security/hosted-glib"), { recursive: true });
  for (const [cargoExit, teeExit] of [
    [0, 0],
    [101, 0],
    [0, 9],
    [101, 9],
  ]) {
    const result = spawnSync("bash", ["--noprofile", "--norc", "-e", "-o", "pipefail"], {
      cwd: root,
      encoding: "utf8",
      input: `cargo() { printf 'test output\\n'; return ${cargoExit}; }\ntee() { cat; return ${teeExit}; }\n${block}\n`,
      timeout: 10000,
    });
    assert.ifError(result.error);
    assert.equal(result.status, cargoExit || teeExit);
    assert.match(result.stdout, /test output/);
    assert.equal(
      readFileSync(join(root, ".cache/p1-security/hosted-glib/test-exits.txt"), "utf8").trim(),
      `${cargoExit} ${teeExit}`,
    );
  }
});


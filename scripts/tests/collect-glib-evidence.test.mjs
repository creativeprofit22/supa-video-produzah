test("missing/failed inspection commands and empty symbols never become no-match success", (t) => {
  const { root } = fixture(t);
  assert.throws(() => command(root, join(root, "missing-tool"), []), /missing-tool.*failed/);
  assert.throws(() => command(root, process.execPath, ["-e", "process.exit(7)"]), /failed \(7\)/);
  const output = join(root, "symbols.txt");
  const receipt = command(
    root,
    process.execPath,
    ["-e", "process.stdout.write('00001234 T unrelated_symbol\\n')"],
    output,
  );
  assert.equal(receipt.status, 0);
  validateSymbols(readFileSync(output, "utf8"));
  for (const text of ["", " \n", "nm: no symbols"]) assert.throws(() => validateSymbols(text));
});

test("scratch creation refuses symlinked parents and Cargo config is not silently ignored", (t) => {
  const { root, out } = fixture(t);
  makeContainedDirectory(root, "scratch/nested");
  assert.equal(contained(root, "scratch/nested", "directory"), join(root, "scratch/nested"));
  symlinkSync(out, join(root, "linked"), process.platform === "win32" ? "junction" : "dir");
  assert.throws(() => makeContainedDirectory(root, "linked/escape"), /Symlink/);
  assert.throws(() => makeContainedDirectory(root, "../escape"), /escape/);
  const home = join(root, "cargo-home");
  mkdirSync(home);
  writeFileSync(join(home, "config.toml"), "[build]\ntarget = 'unexpected'");
  assert.throws(() => rejectConfig(root, home), /Unsupported Cargo config/);
});


test("manifest verifies bytes and rejects tampering, omissions, additions and duplicates", (t) => {
  const f = fixture(t);
  const payload = join(f.root, "payload");
  mkdirSync(payload);
  writeFileSync(join(payload, "one.txt"), "original");
  const entries = [{ path: "one.txt", size: 8, sha256: hashFile(join(payload, "one.txt")) }];
  verifyManifest(payload, entries);
  assert.throws(() => verifyManifest(payload, []), /Manifest/);
  assert.throws(() => verifyManifest(payload, [...entries, ...entries]), /Manifest/);
  assert.throws(() => verifyManifest(payload, [{ ...entries[0], path: "../one.txt" }]), /Manifest/);
  writeFileSync(join(payload, "one.txt"), "tampered");
  assert.throws(() => verifyManifest(payload, entries), /hash/);
  writeFileSync(join(payload, "one.txt"), "original");
  writeFileSync(join(payload, "extra.txt"), "extra");
  assert.throws(() => verifyManifest(payload, entries), /Manifest/);
  assert.equal(walk(payload).length, 2);
});

test("requires exact compiler identity and rejects overrides without dumping values", () => {
  const rustc =
    "release: 1.98.1\ncommit-hash: 48a229cea0123456789\nhost: x86_64-unknown-linux-gnu\n";
  validateToolchain(rustc);
  for (const text of [
    rustc.replace("1.98.1", "1.97.1"),
    rustc.replace("48a229cea", "000000000"),
    rustc.replace("x86_64", "aarch64"),
  ])
    assert.throws(() => validateToolchain(text));
  assert.deepEqual(validateEnvironment({ CARGO_INCREMENTAL: "0", GITHUB_TOKEN: "not captured" }), {
    CARGO_INCREMENTAL: "0",
  });
  for (const key of [
    "RUSTFLAGS",
    "RUSTDOCFLAGS",
    "RUSTC_WRAPPER",
    "RUSTC_WORKSPACE_WRAPPER",
    "RUSTC_BOOTSTRAP",
    "CARGO_ENCODED_RUSTFLAGS",
    "CARGO_TARGET_DIR",
    "CARGO_BUILD_TARGET",
    "CARGO_PROFILE_TEST_DEBUG",
  ])
    assert.throws(
      () => validateEnvironment({ [key]: "private value" }),
      (error) => error.message.includes(key) && !error.message.includes("private value"),
    );
  assert.throws(() => validateEnvironment({ RUSTUP_TOOLCHAIN: "stable" }));
  validateEnvironment({ RUSTUP_TOOLCHAIN: "1.98.1-x86_64-unknown-linux-gnu" });
});


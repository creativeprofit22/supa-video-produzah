function fixture(t) {
  const root = mkdtempSync(join(tmpdir(), "glib-capture-"));
  t.after(() => rmSync(root, { force: true, recursive: true }));
  const build = join(root, TARGET, "debug/build");
  const out = join(build, "glib-fixture/out");
  mkdirSync(out, { recursive: true });
  const executable = join(root, TARGET, "debug/deps/library-hash");
  mkdirSync(join(root, TARGET, "debug/deps"));
  writeFileSync(executable, "fixture only; never executed");
  const script = {
    reason: "build-script-executed",
    package_id: "registry+fixture#glib@0.1.0",
    out_dir: out,
  };
  const artifact = {
    reason: "compiler-artifact",
    package_id: "path+fixture#desktop@0.1.0",
    target: { name: "supa_video_desktop_lib", kind: ["staticlib", "cdylib", "rlib"] },
    profile: { test: true, opt_level: "0", debuginfo: 2, debug_assertions: true },
    features: ["default", "desktop-runtime", "tauri-ipc-test"],
    executable,
    filenames: [executable],
    fresh: false,
  };
  const finished = { reason: "build-finished", success: true };
  const parse = (messages = [script, artifact, finished]) =>
    parseCargo(
      messages
        .map((message) => (typeof message === "string" ? message : JSON.stringify(message)))
        .join("\n"),
      artifact.package_id,
      artifact.features,
    );
  return { root, build, out, executable, script, artifact, finished, parse };
}

test("selects the exact Cargo package/library test, retaining same-job reuse", (t) => {
  const f = fixture(t);
  const unrelated = { ...f.artifact, package_id: "other-package" };
  const release = { ...f.artifact, profile: { ...f.artifact.profile, test: false } };
  f.artifact.fresh = true;
  const parsed = f.parse([
    f.script,
    unrelated,
    release,
    f.artifact,
    f.finished,
    "running 1 test",
    "test result: ok",
  ]);
  assert.equal(parsed.selected.executable, f.executable);
  assert.equal(parsed.selected.fresh, true);
  assert.equal(parsed.buildFinished, true);
  assert.equal(contained(join(f.root, TARGET, "debug"), parsed.selected.executable), f.executable);
});

test("fails closed on missing, duplicate, malformed or incomplete Cargo output", (t) => {
  const f = fixture(t);
  for (const messages of [
    [f.script, f.finished],
    [f.script, f.artifact, f.artifact, f.finished],
    [f.script, f.artifact],
    [f.script, f.artifact, { ...f.finished, success: false }],
    [f.artifact, f.finished],
    ["{broken"],
    [{ reason: "compiler-artifact" }, f.finished],
    [{ ...f.script, out_dir: "relative/out" }, f.artifact, f.finished],
    [f.script, f.artifact, f.finished, f.finished],
    [{ reason: "unexpected" }, f.finished],
  ])
    assert.throws(() => f.parse(messages));
});

